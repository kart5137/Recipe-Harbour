const DICTS: Record<Locale, Dict> = { en, de };

export function dict(lang: Locale): Dict {
  return DICTS[lang];
}

/** Path for a page in a language: localePath("de", "/recipe/en-1?have=x") -> "/de/recipe/en-1?have=x". */
export function localePath(lang: Locale, rest = ""): string {
  return `/${lang}${rest === "/" ? "" : rest}`;
}
