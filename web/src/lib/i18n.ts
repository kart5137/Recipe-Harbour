/**
 * Interface text in English and German. Recipes keep their own language; only the app's
 * own words are translated. `de` is typed as `Dict`, so a missing translation fails to compile.
 */
export const LOCALES = ["en", "de"] as const; // the only intended "as const"
export type Locale = (typeof LOCALES)[number];
export const DEFAULT_LOCALE: Locale = "en";

export function isLocale(x: string): x is Locale {
  return (LOCALES as readonly string[]).includes(x);
}

