"""Write docs/model/MODEL_CARD.md, web/public/model/LICENSE.txt and the photo credits,
from the run's metrics.json and the exported labels.json (no hand-written numbers).

    python model/model_card.py --run v2
"""

from __future__ import annotations

import argparse
import csv
import json
import shutil
from datetime import date
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
WEB_MODEL = ROOT / "web" / "public" / "model"


def pct(x: float | None) -> str:
    return "–" if x is None else f"{100 * x:.0f} %"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--run", default="v2")
    a = ap.parse_args()
    run = HERE / "runs" / a.run
    m = json.loads((run / "metrics.json").read_text(encoding="utf-8"))
    labels = json.loads((WEB_MODEL / "labels.json").read_text(encoding="utf-8"))
    chosen = m["chosen"]
    res = m["results"][chosen]
    test = res["test"]
    by_id = {c["id"]: c for c in labels["classes"]}
    th = labels["thresholds"]
    with (HERE / "data" / "manifest.csv").open(encoding="utf-8") as f:
        rows = list(csv.DictReader(f))
    n_train_real = sum(1 for r in rows if r["split"] == "train" and r["source"] == "openimages")
    n_train_lab = sum(1 for r in rows if r["split"] == "train" and r["source"] == "fruits360")
    n_val = sum(1 for r in rows if r["split"] == "val")
    with (HERE / "data" / "oi_attribution.csv").open(encoding="utf-8") as f:
        credits = list(csv.DictReader(f))

    L = [
        "# Model card: Recipe Harbour produce classifier",
        "",
        f"> Generated by `model/model_card.py` from run `{a.run}` on {date.today().isoformat()}. "
        "Numbers come from the run's `metrics.json`; do not edit by hand.",
        "",
        "## What it does",
        "",
        "Recognises **one fruit or vegetable per photo** and suggests the top 3 ingredients with confidence. "
        "It runs in the browser (TensorFlow.js); photos never leave the device. It is a convenience for "
        "adding ingredients, not a food-safety tool.",
        "",
        "## Model",
        "",
        "- MobileNetV2 (ImageNet weights, 224×224 input) with a softmax head over "
        f"{len(m['classes'])} classes; the top {155 - 100} backbone layers fine-tuned.",
        f"- Exported to TensorFlow.js with 16-bit weights ({labels['weights']}); the exported model gives the "
        f"same top answer as the trained Keras model on {pct(labels['export_agreement'])} of 200 real test "
        "photos. 8-bit quantisation was tried and rejected (it changed most answers).",
        "- Size: about 4.7 MB.",
        "",
        "## Training data",
        "",
        "| Source | Licence | Use | Images |",
        "|---|---|---|---|",
        f"| Open Images V7 (Google), boxes cropped from real photos | images CC BY 2.0 (checked per image), "
        f"annotations CC BY 4.0 | training, validation, test | {n_train_real:,} train · {n_val:,} val · "
        f"{test['n']:,} test |",
        f"| Fruits-360 (Mihai Oltean), lab photos on white | CC BY-SA 4.0 | training only | {n_train_lab:,} |",
        "",
        "- Only real photos (no drawings), only images whose own metadata says CC BY 2.0, no images needing "
        "rotation. Splits are by **photo**, so crops of the same photo are never in two splits.",
        f"- {len(credits):,} Open Images photos were used; every author is credited in "
        "[`model/OPEN_IMAGES_CREDITS.csv`](../../model/OPEN_IMAGES_CREDITS.csv).",
        "- The model was chosen on the validation set; the test set was used once per candidate, for reporting.",
        "",
        "## How well it works (real photos it never saw)",
        "",
        f"**Overall:** top-1 {pct(test['top1'])}, top-3 {pct(test['top3'])} on {test['n']:,} real-photo crops "
        f"(macro top-1 across classes {pct(test['macro_top1'])}).",
        "",
        "Runs compared (same test set):",
        "",
        "| Run | Training examples | Test top-1 | Test top-3 |",
        "|---|---|---|---|",
    ]
    for name, r in m["results"].items():
        L.append(f"| {name}{' (chosen)' if name == chosen else ''} | {r['train_images']:,} | "
                 f"{pct(r['test']['top1'])} | {pct(r['test']['top3'])} |")
    L += [
        "",
        "Training examples: the head-only runs count each training image twice (the original and one "
        "augmented copy); fine-tuning uses each image once per pass, with fresh random augmentation. "
        "`real_photos_only` leaves out the Fruits-360 lab photos.",
        "",
        f"A class is **offered in the app** only if, on at least {th['min_test']} real test photos, the right "
        f"answer is first at least {pct(th['top1'])} of the time and in the top 3 at least {pct(th['top3'])}.",
        "",
        "| Ingredient | Test photos | Top-1 | Top-3 | In the app |",
        "|---|---|---|---|---|",
    ]
    for c, v in sorted(test["per_class"].items(), key=lambda kv: -(kv[1]["top1"] or 0)):
        L.append(f"| {c.replace('_', ' ')} | {v['n']} | {pct(v['top1'])} | {pct(v['top3'])} | "
                 f"{'yes' if by_id[c]['offered'] else 'no'} |")
    L += [
        "",
        "Small test sets (under about 50 photos) give rough numbers: one photo moves the score by 2–5 points.",
        "",
        "## Known weaknesses",
        "",
        "Most frequent mix-ups on the test set:",
        "",
    ]
    L += [f"- {x['true']} taken for {x['pred']}: {x['count']} times" for x in test["top_confusions"][:8]]
    L += [
        "",
        "- Zucchini and cucumber look alike in photos; the right one is usually in the top 3 but not first.",
        "- Apple, pear, mango and fig are not reliable enough to offer.",
        "- Not trained for: several items in one photo, cut or cooked food, packaged food "
        "(use the barcode scanner), onions, garlic, lemons and other produce without real-photo test data.",
        "",
        "## Licence",
        "",
        "The model weights are a derivative of Fruits-360 (CC BY-SA 4.0) and are released under **CC BY-SA 4.0**, "
        "with credit to Fruits-360 (Mihai Oltean), Open Images V7 (Google, CC BY 4.0 annotations) and the "
        "Open Images photographers (CC BY 2.0). MobileNetV2 architecture and ImageNet weights from TensorFlow/Keras "
        "(Apache 2.0).",
        "",
    ]
    out = ROOT / "docs" / "model"
    out.mkdir(parents=True, exist_ok=True)
    (out / "MODEL_CARD.md").write_text("\n".join(L), encoding="utf-8")

    shutil.copyfile(HERE / "data" / "oi_attribution.csv", HERE / "OPEN_IMAGES_CREDITS.csv")
    (WEB_MODEL / "LICENSE.txt").write_text(
        "Recipe Harbour produce classifier (TensorFlow.js)\n\n"
        "Licence: CC BY-SA 4.0 (https://creativecommons.org/licenses/by-sa/4.0/)\n\n"
        "Trained on:\n"
        "- Fruits-360 by Mihai Oltean, CC BY-SA 4.0 (https://github.com/fruits-360)\n"
        "- Open Images V7 (https://storage.googleapis.com/openimages/web/index.html): annotations CC BY 4.0\n"
        "  by Google LLC; photos CC BY 2.0 by their authors, listed in model/OPEN_IMAGES_CREDITS.csv\n"
        "  of the Recipe Harbour source repository.\n"
        "- MobileNetV2 ImageNet weights from TensorFlow/Keras (Apache 2.0).\n\n"
        "Details and test results: docs/model/MODEL_CARD.md in the source repository.\n",
        encoding="utf-8",
    )
    print(f"model card, licence and {len(credits)} credits written")


if __name__ == "__main__":
    main()
