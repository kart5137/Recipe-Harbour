"""Write the model card, the licence file, the Hugging Face page and the photo credits for the
image-text photo model, from the saved results (no hand-written numbers).

    .venv-clip/Scripts/python model/clip_model_card.py

Reads model/runs/clip/*.json, model/runs/clip/export/<key>/variants.json and
web/public/model/labels.json. Writes docs/model/MODEL_CARD.md, web/public/model/LICENSE.txt,
model/hf/ (README.md + LICENSE.txt + the model files, ready to upload) and appends the new
photos' authors to model/OPEN_IMAGES_CREDITS.csv.
"""

from __future__ import annotations

import csv
import json
import shutil
from datetime import date
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
RUNS = HERE / "runs" / "clip"
WEB_MODEL = ROOT / "web" / "public" / "model"
HF = HERE / "hf"

CANDIDATES = [  # zero-shot comparison, in the order they were tried
    ("tinyclip-8m", "TinyCLIP ViT-8M/16 (Microsoft, MIT)"),
    ("tinyclip-40m", "TinyCLIP ViT-40M/32 (Microsoft, MIT)"),
    ("tinyclip-39m", "TinyCLIP ViT-39M/16 (Microsoft, MIT)"),
    ("tinyclip-61m", "TinyCLIP ViT-61M/32 (Microsoft, MIT)"),
    ("openai-b32", "CLIP ViT-B/32 (OpenAI, MIT)"),
    ("laion-b32", "CLIP ViT-B/32 LAION-2B (MIT)"),
    ("siglip2-b16", "SigLIP 2 base, patch 16 (Google, Apache 2.0)"),
]


def pct(x: float | None) -> str:
    return "–" if x is None else f"{100 * x:.0f} %"


def load(p: Path) -> dict:
    return json.loads(p.read_text(encoding="utf-8"))


def main() -> None:
    labels = load(WEB_MODEL / "labels.json")
    key, variant = labels["version"].rsplit("-", 1)
    variants = load(RUNS / "export" / key / "variants.json")
    head = load(RUNS / f"head-{key}-{variant}.json")
    head_fp = load(RUNS / f"head-{key}.json")
    th = labels["thresholds"]
    classes = labels["classes"]
    offered = [c for c in classes if c["offered"]]
    v = variants[variant]
    with (HERE / "data" / "wholetrain.csv").open(encoding="utf-8") as f:
        wholetrain = list(csv.DictReader(f))
    with (HERE / "data" / "whole.csv").open(encoding="utf-8") as f:
        whole = list(csv.DictReader(f))
    n_crops_test = load(RUNS / "laion-b32.json")["sets"]["crops"]["n"]

    conf_n = sum(c["confident"] for c in offered)
    conf_right = sum(c["confident"] * c["confident_right"] for c in offered) / conf_n
    zs_rows = []
    for k, name in CANDIDATES:
        p = RUNS / f"{k}.json"
        if p.exists():
            r = load(p)
            zs_rows.append(f"| {name} | {r['vision_params_m']} M | {pct(r['sets']['crops']['top1'])} | {pct(r['sets']['whole']['top1'])} | {pct(r['sets']['whole']['top3'])} |")
    zs_rows.append(f"| SigLIP 2 base, patch 32 (Google, Apache 2.0, chosen) | 94.6 M | {pct(head_fp['sets']['crops']['zero_shot_top1'])} | {pct(head_fp['sets']['whole']['zero_shot_top1'])} | – |")
    head_rows = []
    for k, name in (("tinyclip-39m", "TinyCLIP ViT-39M/16"), (key, "SigLIP 2 base, patch 32 (chosen)")):
        p = RUNS / f"head-{k}.json"
        if p.exists():
            r = load(p)
            head_rows.append(f"| {name} | {pct(r['sets']['crops']['top1'])} / {pct(r['sets']['crops']['top3'])} | {pct(r['sets']['whole']['top1'])} / {pct(r['sets']['whole']['top3'])} |")
    var_rows = [f"| {n} | {d['mb']} MB | {pct(d['sets']['crops']['top1'])} / {pct(d['sets']['crops']['top3'])} | {pct(d['sets']['whole']['top1'])} / {pct(d['sets']['whole']['top3'])} | {pct(d['sets']['whole']['same_answer_as_fp32'])} |"
                for n, d in variants.items()]

    def row(c: dict) -> str:
        return (f"| {c['id'].replace('_', ' ')} | {c['test_photos']} | {pct(c['top1'])} | {pct(c['top3'])} | "
                f"{c['confident']} | {pct(c['confident_right'])} | {'yes' if c['offered'] else 'no'} |")

    measured = sorted((c for c in classes if c["test_photos"]), key=lambda c: (-c["offered"], -(c["top1"] or 0)))
    untested = [c["id"].replace("_", " ") for c in classes if not c["test_photos"]]
    weak = [c for c in classes if c["test_photos"] >= th["min_test"] and not c["offered"]]

    card = f"""# Model card: Recipe Harbour photo recogniser

> Generated by `model/clip_model_card.py` on {date.today().isoformat()} from the saved results in `model/runs/clip/`. Do not edit by hand.

## What it does

Recognises **one fruit, vegetable or herb per photo** and suggests ingredients from the Recipe Harbour vocabulary, with a probability. It runs in the browser (ONNX Runtime Web); photos never leave the device. It is a convenience for adding ingredients, not a food-safety tool.

It replaces the R6 model (MobileNetV2, 24 classes, 10 offered), which did not know onion or garlic.

## How it works

- An image-text model, **Google SigLIP 2 base, patch 32, 256 × 256** (`{labels['model']}`, Apache 2.0), turns the photo into a vector.
- Each of the {len(classes)} ingredients has a few names ("radish" also covers turnip and parsnip). Their text vectors from the same model are the starting point of the ingredient head; the head was then tuned on real photos, with a penalty that keeps it close to the text (strength {head['lam']}, {head['epochs']} passes, chosen on held-out training photos). Ingredients without training photos still work from their names.
- An ingredient's score is its best-matching name; a softmax turns scores into the percentages the app shows.
- Red onion and shallot are answered as **onion**: the model cannot tell them apart reliably.
- Only the image half of the model ships. Its matrix weights are stored in 4 bits (blocks of 32), other large weights in 16 bits: **{v['mb']} MB**. The ingredient head is {round((WEB_MODEL / 'head.bin').stat().st_size / 1e3)} kB.

## Data

| Source | Licence | Use | Photos |
|---|---|---|---|
| Open Images V7 box crops (R6) | photos CC BY 2.0, annotations CC BY 4.0 | head training (at most 150 per ingredient) | see `model/data/manifest.csv` |
| Open Images V7 whole train photos with one human-verified produce label | photos CC BY 2.0, labels CC BY 4.0 | head training, 15 % held out for choosing settings | {len(wholetrain):,} |
| Fruits-360 (Mihai Oltean), lab photos | CC BY-SA 4.0 | head training (inside the crop sample) | – |
| Open Images V7 test box crops (R6 test set) | as above | **test** | {n_crops_test:,} |
| Open Images V7 whole test + validation photos with one human-verified produce label | as above | **test** | {len(whole):,} |

- Only photos whose own metadata says CC BY 2.0, not rotated. Every author is credited in [`model/OPEN_IMAGES_CREDITS.csv`](../../model/OPEN_IMAGES_CREDITS.csv).
- Train and test photos come from different Open Images splits, so no photo is in both.
- The whole photos often show other things too, and a few labels are debatable (spring onions with big bulbs, a salad box labelled cucumber that shows mostly red onion), so these numbers are a lower bound for a close-up phone photo of one item.

## How well it works

Across all {len(classes)} ingredients (the R6 model chose among 24).

**Shipped model ({variant}):** right first time {pct(v['sets']['crops']['top1'])} / in the top 3 {pct(v['sets']['crops']['top3'])} on the {n_crops_test:,} test crops; {pct(v['sets']['whole']['top1'])} / {pct(v['sets']['whole']['top3'])} on the {len(whole):,} whole photos. (R6 model: 74 % / 90 % on the crops, over 24 classes.)

When the app says "Looks like X" (probability at least {pct(th['confident'])} and X offered), X is right on {pct(conf_right)} of those test photos ({conf_n:,} answers); per ingredient in the table below.

### Models compared without training (zero-shot)

| Model | Image half | Crops, right first | Whole, right first | Whole, top 3 |
|---|---|---|---|---|
{chr(10).join(zs_rows)}

### With the trained ingredient head (full precision), right first / top 3

| Model | Crops | Whole photos |
|---|---|---|
{chr(10).join(head_rows)}

SigLIP 2 patch 32 was chosen: without training it is about as accurate as patch 16, but it looks at 64 image patches instead of 196, so a photo needs about a third of the computing, which matters on a phone. TinyCLIP would be about half the size but is clearly less accurate. (Patch 16 was not trained with a head.)

### Smaller versions of the chosen model (right first / top 3)

| Version | Size | Crops | Whole photos | Same answer as full precision (whole) |
|---|---|---|---|---|
{chr(10).join(var_rows)}

All rows use the shipped ingredient head. 8-bit quantisation breaks this model; 4-bit with 16-bit storage of the remaining weights keeps almost all of it and is what ships. Re-fitting the head to the 4-bit model's own outputs did not change the results.

### Per ingredient (both test sets together)

An ingredient is **offered** (suggested by the app) if, on at least {th['min_test']} test photos of it, the right answer is in the top 3 at least {pct(th['top3'])} of the time, **and**, over at least {th['min_test']} answers where the app would say "Looks like X", X is right at least {pct(th['precision'])} of the time. The second part is what a user sees. Ingredients that are not offered are never suggested; the app asks you to type them instead.

| Ingredient | Test photos | Right first | In top 3 | "Looks like" answers | …of those right | Offered |
|---|---|---|---|---|---|---|
{chr(10).join(row(c) for c in measured)}

**Offered ({len(offered)}):** {', '.join(c['id'].replace('_', ' ') for c in offered)}.

No test photos (never offered): {', '.join(untested)}.

## Known weaknesses

- Measured but below the bar: {', '.join(f"{c['id'].replace('_', ' ')} ({pct(c['top1'])} right first)" for c in sorted(weak, key=lambda c: c['top1'] or 0))}.
- Cucumber and zucchini look alike; berries are often confused with each other.
- Not trained for several items in one photo, cut or cooked food, or packaged food (use the barcode scanner).
- About 0.7 s per photo on a desktop browser (one WebAssembly thread); slower on phones.

## Licence

- `vision.onnx`: SigLIP 2 by Google, Apache 2.0, quantised (modified) by Recipe Harbour.
- `head.bin` (ingredient head): trained on Fruits-360 (CC BY-SA 4.0) and Open Images (photos CC BY 2.0, annotations CC BY 4.0), released under **CC BY-SA 4.0**.
"""
    (ROOT / "docs" / "model" / "MODEL_CARD.md").write_text(card, encoding="utf-8")

    licence = f"""Recipe Harbour photo recogniser ({labels['version']})

vision.onnx
  SigLIP 2 base, patch 32, 256 px ({labels['model']}) by Google LLC, Apache License 2.0
  (https://www.apache.org/licenses/LICENSE-2.0). Modified: only the image encoder, weights
  quantised to 4 bits (matrices) and 16 bits (other large weights).

head.bin, labels.json (ingredient head and metadata)
  Licence: CC BY-SA 4.0 (https://creativecommons.org/licenses/by-sa/4.0/). Trained on:
  - Fruits-360 by Mihai Oltean, CC BY-SA 4.0 (https://github.com/fruits-360)
  - Open Images V7 (https://storage.googleapis.com/openimages/web/index.html): annotations
    CC BY 4.0 by Google LLC; photos CC BY 2.0 by their authors, listed in
    model/OPEN_IMAGES_CREDITS.csv of https://github.com/kart5137/Recipe-Harbour

Details and test results: docs/model/MODEL_CARD.md in the source repository.
"""
    (WEB_MODEL / "LICENSE.txt").write_text(licence, encoding="utf-8")

    # Hugging Face page and the files to upload.
    HF.mkdir(exist_ok=True)
    for f in ("vision.onnx", "head.bin", "labels.json", "LICENSE.txt"):
        shutil.copy(WEB_MODEL / f, HF / f)
    front = """---
license: other
license_name: apache-2.0-and-cc-by-sa-4.0
license_link: https://github.com/kart5137/Recipe-Harbour/blob/main/web/public/model/LICENSE.txt
library_name: onnxruntime
pipeline_tag: image-classification
base_model: google/siglip2-base-patch32-256
tags:
- food
- produce
- onnx
- recipe-harbour
---

"""
    hf_card = card.replace("](../../model/OPEN_IMAGES_CREDITS.csv)", "](https://github.com/kart5137/Recipe-Harbour/blob/main/model/OPEN_IMAGES_CREDITS.csv)")
    hf_card = hf_card.replace("> Generated by `model/clip_model_card.py`", "> Model files for [Recipe Harbour](https://github.com/kart5137/Recipe-Harbour). Generated by `model/clip_model_card.py`")
    (HF / "README.md").write_text(front + hf_card, encoding="utf-8")

    # Credits: add the authors of the new photos (training and test) not already listed.
    credits = HERE / "OPEN_IMAGES_CREDITS.csv"
    with credits.open(encoding="utf-8", newline="") as f:
        have = {r["image"] for r in csv.DictReader(f)}
    added = 0
    with credits.open("a", encoding="utf-8", newline="") as f:
        w = csv.writer(f)
        for r in wholetrain + whole:
            if r["image"] not in have:
                have.add(r["image"])
                w.writerow([r["image"], r["author"], r["author_url"], r["title"], r["source_url"], r["license"]])
                added += 1
    print(f"model card, licence and Hugging Face files written; {added} photo credits added ({len(have)} in total)")


if __name__ == "__main__":
    main()
