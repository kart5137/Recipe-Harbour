"""Ingredient coverage report: how much of the recipe data the vocabulary understands."""

from __future__ import annotations

import re
from collections import Counter

from .ingredients import Vocabulary, norm, parse_quantity, vocab

_STRIP_WORDS = re.compile(
    r"\b(\d+[\d/.,]*|chopped|diced|sliced|minced|fresh|finely|large|small|medium|to taste|taste|for|of|and|or|"
    r"the|a|optional|ground|grated|cut|into|pieces|peeled|about|cup|cups|tbsp|tsp|g|kg|ml|oz|lb|"
    r"gehackt|gewuerfelt|frisch|frische|frischer|nach|belieben|etwas|und|oder|zum|fuer|ca|evtl|klein|grosse|el|tl)\b"
)


def _residue(text: str) -> str:
    """What is left of an unmatched line once quantities, units and common words are gone."""
    t = norm(re.sub(r"\([^)]*\)", " ", text))
    t = _STRIP_WORDS.sub(" ", t)
    return re.sub(r"\s+", " ", t).strip()


def coverage_md(recipes: list[dict], now: str, v: Vocabulary | None = None) -> str:
    v = v or vocab()
    L = [
        "# Ingredient coverage",
        "",
        f"> Generated by `rh build` on {now}. Do not edit by hand; re-run the pipeline.",
        "",
        f"Vocabulary: {len(v.items)} canonical ingredients, {len(v.index['en'])} English and "
        f"{len(v.index['de'])} German names (`pipeline/vocab/ingredients.tsv`).",
        "",
        "## Lines understood",
        "",
        "| | English | German |",
        "|---|---|---|",
    ]
    stats = {}
    for lang in ("en", "de"):
        rs = [r for r in recipes if r["lang"] == lang]
        lines = [(it, src) for r in rs for it, src in zip(
            [i for g in r["ingredient_groups"] for i in g["items"]], r["_match_sources"], strict=True)]
        matched = [x for x in lines if x[0]["ids"]]
        full = [r for r in rs if all(i["ids"] or i["optional"] for g in r["ingredient_groups"] for i in g["items"])]
        qty = [x for x in lines if x[0]["qty"]]
        stats[lang] = {
            "recipes": rs, "lines": lines, "matched": matched, "full": full,
            "src": Counter(src for _, src in matched), "qty": qty,
            "unmatched": Counter(_residue(it["text"]) for it, _ in lines if not it["ids"]),
        }

    def pct(n, d):
        return f"{100 * n / d:.1f} %" if d else "–"

    en, de = stats["en"], stats["de"]
    L += [
        f"| Ingredient lines | {len(en['lines'])} | {len(de['lines'])} |",
        f"| **Lines with at least one ingredient** | **{pct(len(en['matched']), len(en['lines']))}** | "
        f"**{pct(len(de['matched']), len(de['lines']))}** |",
        f"| … found in the text | {pct(en['src']['text'], len(en['lines']))} | "
        f"{pct(de['src']['text'], len(de['lines']))} |",
        f"| … found only through a cookbook link | {pct(en['src']['link'], len(en['lines']))} | "
        f"{pct(de['src']['link'], len(de['lines']))} |",
        f"| Lines with a quantity | {pct(len(en['qty']), len(en['lines']))} | "
        f"{pct(len(de['qty']), len(de['lines']))} |",
        f"| **Recipes with every line understood** | **{pct(len(en['full']), len(en['recipes']))}** | "
        f"**{pct(len(de['full']), len(de['recipes']))}** |",
    ]

    L += ["", "## Diet labels", "", "| | English | German |", "|---|---|---|"]
    for label in ("vegan", "vegetarian", "none", ""):
        name = {"none": "contains meat or fish", "": "unknown"}.get(label, label)
        row = []
        for s in (en, de):
            rs = s["recipes"]
            n_wiki = sum(1 for r in rs if r["diet"] == label and r["diet_source"] == "wiki")
            n_inf = sum(1 for r in rs if r["diet"] == label and r["diet_source"] != "wiki")
            row.append(f"{n_wiki + n_inf} ({n_wiki} from the wiki)" if n_wiki else f"{n_wiki + n_inf}")
        L.append(f"| {name} | {row[0]} | {row[1]} |")
    L += [
        "",
        "Vegetarian/vegan is only inferred when every non-optional line was understood, so an",
        "unrecognised line (which could be bacon) leaves the label unknown.",
    ]

    for lang, s in stats.items():
        L += ["", f"## Most common unmatched ({lang})", ""]
        L += [f"- `{t or '(empty after cleaning)'}` ({n})" for t, n in s["unmatched"].most_common(40)]

    use = Counter(i for r in recipes for i in r["ingredient_ids"])
    L += ["", "## Ingredients used in most recipes", ""]
    L += [", ".join(f"{i} ({n})" for i, n in use.most_common(60))]
    # Kitchen items (non_food) are understood but deliberately not searchable.
    unused = sorted(i for i in set(v.items) - set(use) if "non_food" not in v.flags(i))
    listed = f" ({', '.join(unused)})" if unused else ""
    L += ["", f"Vocabulary entries not found in any recipe: {len(unused)}{listed}"]

    # Quantity sanity: units seen
    units = Counter(i["unit"] for r in recipes for g in r["ingredient_groups"] for i in g["items"] if i["unit"])
    L += ["", "## Units recognised", "", ", ".join(f"{u} ({n})" for u, n in units.most_common())]
    _ = parse_quantity  # documented dependency: quantities come from ingredients.parse_quantity
    L.append("")
    return "\n".join(L)
