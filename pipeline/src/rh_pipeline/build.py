"""Parse the raw pages, write the dataset and its profile.

Outputs
- data/recipes.json        all kept recipes (CC BY-SA 4.0, see data/LICENSE.md)
- data/recipes.meta.json   when, from which revisions, counts
- docs/data/PROFILE.md     what was kept and dropped, field coverage, quality notes
- docs/data/INGREDIENTS.md how much of the ingredient text the vocabulary understands
"""

from __future__ import annotations

import json
import logging
import statistics
from collections import Counter
from datetime import UTC, datetime
from pathlib import Path

from .config import DOCS_DIR, OUT_DIR, RAW_DIR, SOURCES
from .coverage import coverage_md
from .fetch import read_pages
from .ingredients import enrich_recipe, vocab
from .parse import Dropped, parse_page

log = logging.getLogger(__name__)


def _pct(n: int, d: int) -> str:
    return f"{100 * n / d:.0f} %" if d else "–"


def _dist(values: list[int]) -> str:
    if not values:
        return "–"
    v = sorted(values)
    p90 = v[min(len(v) - 1, int(0.9 * len(v)))]
    return f"min {v[0]} · median {statistics.median(v):g} · p90 {p90} · max {v[-1]}"


def build(raw_dir: Path = RAW_DIR, out_dir: Path = OUT_DIR, docs_dir: Path = DOCS_DIR) -> dict:
    now = datetime.now(UTC).replace(microsecond=0).isoformat()
    v = vocab()
    recipes: list[dict] = []
    stats: dict[str, dict] = {}
    for lang, source in SOURCES.items():
        pages = read_pages(lang, raw_dir)
        kept, dropped = [], Counter()
        dropped_examples: dict[str, list[str]] = {}
        for p in pages:
            try:
                kept.append(enrich_recipe(parse_page(p, source).to_dict(), v))
            except Dropped as e:
                dropped[e.reason] += 1
                dropped_examples.setdefault(e.reason, []).append(p["title"])
        kept.sort(key=lambda r: r["title"].casefold())
        recipes += kept
        stats[lang] = {
            "fetched": len(pages),
            "kept": len(kept),
            "dropped": dict(dropped),
            "dropped_examples": {k: sorted(v)[:6] for k, v in dropped_examples.items()},
            "recipes": kept,
            "fetched_at_latest_revision": max((p["timestamp"] for p in pages), default=""),
        }
        log.info("%s: %d fetched, %d kept, dropped %s", lang, len(pages), len(kept), dict(dropped))

    docs_dir.mkdir(parents=True, exist_ok=True)
    (docs_dir / "INGREDIENTS.md").write_text(coverage_md(recipes, now, v), encoding="utf-8")
    for r in recipes:
        r.pop("_match_sources", None)
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "recipes.json").write_text(
        json.dumps(recipes, ensure_ascii=False, separators=(",", ":")), encoding="utf-8"
    )
    meta = {
        "built_at": now,
        "licence": "CC BY-SA 4.0",
        "sources": {
            lang: {
                "wiki": SOURCES[lang].api.rsplit("/w/", 1)[0],
                "category": SOURCES[lang].category,
                "fetched_pages": s["fetched"],
                "recipes": s["kept"],
                "dropped": s["dropped"],
            }
            for lang, s in stats.items()
        },
        "total_recipes": len(recipes),
    }
    (out_dir / "recipes.meta.json").write_text(json.dumps(meta, indent=2, ensure_ascii=False), encoding="utf-8")
    docs_dir.mkdir(parents=True, exist_ok=True)
    (docs_dir / "PROFILE.md").write_text(_profile_md(stats, now), encoding="utf-8")
    return meta


def _profile_md(stats: dict, now: str) -> str:
    L = [
        "# Recipe data profile",
        "",
        f"> Generated by `rh build` on {now}. Do not edit by hand; re-run the pipeline.",
        "",
        "## Kept and dropped",
        "",
        "| | English (Cookbook) | German (Kochbuch) |",
        "|---|---|---|",
    ]
    en, de = stats.get("en", {}), stats.get("de", {})
    reasons = sorted(set(en.get("dropped", {})) | set(de.get("dropped", {})))
    L.append(f"| Pages in category | {en.get('fetched', 0)} | {de.get('fetched', 0)} |")
    L.append(f"| **Recipes kept** | **{en.get('kept', 0)}** | **{de.get('kept', 0)}** |")
    for r in reasons:
        L.append(f"| Dropped: {r} | {en['dropped'].get(r, 0)} | {de['dropped'].get(r, 0)} |")
    L += ["", "Dropped examples (first few by title):", ""]
    for lang, s in stats.items():
        for reason, titles in s["dropped_examples"].items():
            L.append(f"- `{lang}` {reason}: " + "; ".join(titles))

    def cov(s: dict, pred) -> str:
        rs = s.get("recipes", [])
        return f"{_pct(sum(1 for r in rs if pred(r)), len(rs))}"

    fields = [
        ("Servings (parsed to a number)", lambda r: r["servings"]),
        ("Time (parsed to minutes)", lambda r: r["minutes"]),
        ("Time given but not parsed", lambda r: r["time_text"] and not r["minutes"]),
        ("Difficulty (1–5)", lambda r: r["difficulty"]),
        ("Category", lambda r: r["category"]),
        ("Cuisine", lambda r: r["cuisine"]),
        ("Diet from the source (vegetarian/vegan/none)", lambda r: r.get("diet_source") == "wiki"),
        ("Image named", lambda r: r["image"]),
        ("Introduction text", lambda r: r["description"]),
        ("Equipment list", lambda r: r["equipment"]),
        ("Ingredient groups (more than one)", lambda r: len(r["ingredient_groups"]) > 1),
    ]
    L += ["", "## Field coverage (share of kept recipes)", "", "| Field | English | German |", "|---|---|---|"]
    for name, pred in fields:
        L.append(f"| {name} | {cov(en, pred)} | {cov(de, pred)} |")

    def sizes(s, f):
        return _dist([f(r) for r in s.get("recipes", [])])

    n_ing = lambda r: sum(len(g["items"]) for g in r["ingredient_groups"])  # noqa: E731
    total_en = sum(n_ing(r) for r in en.get("recipes", []))
    total_de = sum(n_ing(r) for r in de.get("recipes", []))
    L += [
        "",
        "## Size",
        "",
        "| | English | German |",
        "|---|---|---|",
        f"| Ingredient lines per recipe | {sizes(en, n_ing)} | {sizes(de, n_ing)} |",
        f"| Steps per recipe | {sizes(en, lambda r: len(r['steps']))} | {sizes(de, lambda r: len(r['steps']))} |",
        f"| Ingredient lines in total | {total_en} | {total_de} |",
    ]

    def years(s):
        c = Counter(r["revision_timestamp"][:4] for r in s.get("recipes", []))
        return ", ".join(f"{y}: {n}" for y, n in sorted(c.items()))

    L += ["", "## Last edited (year of the revision used)", ""]
    for lang, s in stats.items():
        L.append(f"- `{lang}`: {years(s)}")

    for lang, s in stats.items():
        rs = s.get("recipes", [])
        cats = Counter(r["category"] for r in rs if r["category"]).most_common(15)
        L += ["", f"## Top categories ({lang})", ""]
        L += [f"- {c} ({n})" for c, n in cats] or ["- none recorded"]
        unparsed = Counter(r["time_text"] for r in rs if r["time_text"] and not r["minutes"]).most_common(10)
        if unparsed:
            L += ["", f"Time texts not parsed ({lang}, most common):", ""]
            L += [f"- “{t}” ({n})" for t, n in unparsed]
        diets = Counter(r["diet"] for r in rs if r["diet"])
        if diets:
            L += ["", f"Diet field ({lang}): " + ", ".join(f"{k} {v}" for k, v in diets.most_common())]

    L += [
        "",
        "## Notes",
        "",
        "- Licence: CC BY-SA 4.0. Each recipe keeps its page URL, history (authors) URL and revision id.",
        "- Ingredient lines are still raw text here; R2 parses them into canonical ingredients.",
        "- Diet tags for English recipes are not in the source; R2/R8 infer them from ingredients.",
        "",
    ]
    return "\n".join(L)
